const CK45_SHEET_THICKNESSES = [8, 10, 12, 15, 20, 25, 30, 35] as const;

function buildCk45WeightRows(): readonly (readonly string[])[] {
  return CK45_SHEET_THICKNESSES.map((thicknessMm) => {
    // فرمول وزن ورق استاندارد: طول (۶ متر) × عرض (۲ متر) × ضخامت (میلی‌متر) × چگالی فولاد (۷٫۸۵)
    const sheetWeightKg = Math.round(6 * 2 * thicknessMm * 7.85);
    const kgPerSqMeter = (thicknessMm * 7.85).toLocaleString("fa-IR", {
      minimumFractionDigits: 1,
      maximumFractionDigits: 1,
    });
    return [
      `${toPersianDigits(String(thicknessMm))} میلی‌متر`,
      "۶ × ۲ متر (۱۲ مترمربع)",
      `${kgPerSqMeter} کیلوگرم`,
      `${sheetWeightKg.toLocaleString("fa-IR")} کیلوگرم`,
    ];
  });
}

